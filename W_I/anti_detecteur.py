class MetadataCleaner:
    """
    Classe de nettoyage anti-détection : 
    1. Supprime les métadonnées (dates, auteurs, etc.).
    2. Retire les marqueurs IA du contenu textuel.
    3. Humanise le texte selon différents styles linguistiques.
    4. Nettoie les métadonnées des fichiers binaires (PDF, Office, Image).
    """
    def __init__(self):
        # Extensions de fichiers gérées
        self.text_extensions = ['.txt', '.md', '.py', '.js', '.html', '.css', '.xml', '.json']
        self.image_extensions = ['.jpg', '.jpeg', '.png', '.gif', '.bmp', '.tiff']
        self.document_extensions = ['.pdf', '.docx', '.xlsx', '.pptx']

    # ------------------------------------------------------------
    #  MÉTHODES DE NETTOYAGE DES FICHIERS (I/O)
    # ------------------------------------------------------------
    def clean_file_metadata(self, file_path: Path) -> bool:
        """Point d'entrée principal pour le nettoyage des métadonnées."""
        print(f"\n[CLEANING] Démarrage du nettoyage de : {file_path}")
        try:
            # Utilisation du chemin absolu (resolve()) pour plus de sécurité.
            safe_path = file_path.resolve() 
            _, ext = os.path.splitext(str(safe_path).lower())
            self._modify_file_dates(safe_path)

            if ext in self.text_extensions:
                self._clean_text_file(safe_path)
            elif ext in self.document_extensions:
                self._clean_document_file(safe_path)
            elif ext in self.image_extensions and PILLOW_INSTALLED:
                self._clean_image_file(safe_path)

            return True
        except Exception as e:
            print(f"[ERREUR] Échec du nettoyage global de {file_path} : {type(e).__name__}: {e}")
            return False

    def _modify_file_dates(self, file_path: Path):
        """Modifie les dates d'accès et de modification."""
        days = random.randint(1, 365)
        hours = random.randint(0, 23)
        minutes = random.randint(0, 59)
        mod = time.time() - (days * 86400) - (hours * 3600) - (minutes * 60)
        create = mod - random.randint(3600, 86400 * 7)
        os.utime(str(file_path), (mod, create))

    def _clean_text_file(self, file_path: Path):
        """Supprime les marqueurs IA et autres traces de génération dans le texte."""
        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()

            patterns = [
                r'generated by.*?ai', r'created with.*?ai', r'powered by.*?ai',
                r'using.*?ai', r'ai-generated', r'gpt-\d', r'claude', r'gemini',
                r'bard', r'chatgpt', r'openai', r'anthropic', r'google',
                r'microsoft', r'meta', r'automatically generated',
                r'machine-generated', r'generated on \d{4}-\d{2}-\d{2}',
            ]

            for p in patterns:
                content = re.sub(p, "", content, flags=re.IGNORECASE)

            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)
        except Exception as e:
             print(f" [ERREUR] Problème de lecture/écriture dans le fichier texte ({file_path}) : {e}")

    def _clean_document_file(self, file_path: Path):
        """Contrôle l'appel au nettoyage PDF ou Office en fonction de l'extension."""
        _, ext = os.path.splitext(str(file_path).lower())
        if ext == ".pdf" and PYPDF2_INSTALLED:
            self._clean_pdf_metadata(file_path)
        elif ext in ['.docx', '.xlsx', '.pptx']:
            self._clean_office_metadata(file_path)
        else:
             print(f" [AVERTISSEMENT] Format de document non géré par le cleaner ({ext}).")

    def _clean_pdf_metadata(self, file_path: Path):
        """Nettoie les métadonnées d'un fichier PDF en réécrivant le contenu."""
        # Création du nom temp sécurisé avec l'extension originale.
        temp = f"{file_path}_temp_{random.randint(100, 999)}.pdf"

        try:
            reader = PyPDF2.PdfReader(str(file_path))
            writer = PyPDF2.PdfWriter()

            for page in reader.pages:
                writer.add_page(page)

            clean_metadata = {k: "" for k in [
                "/Creator", "/Producer", "/Author", "/Title",
                "/Subject", "/Keywords", "/CreationDate", "/ModDate"
            ]}
            writer.add_metadata(clean_metadata)

            with open(temp, "wb") as out:
                writer.write(out)

            shutil.move(temp, str(file_path)) # Remplacement atomique
        except Exception as e:
            print(f" [ERREUR] Échec critique lors du nettoyage PDF : {type(e).__name__}: {e}")
        finally:
             if os.path.exists(temp):
                os.remove(temp)

    def _clean_office_metadata(self, file_path: Path):
        """Nettoie les métadonnées des documents Office (ZIP -> Clean XML -> ZIP)."""
        base = os.path.splitext(file_path)[0]
        temp_dir = f"{base}_temp_{random.randint(1, 999)}" 
        temp_file = f"{base}_temp{os.path.splitext(file_path)[1]}"

        try:
            with zipfile.ZipFile(str(file_path), "r") as z:
                z.extractall(temp_dir)

            for xml_file in ["core.xml", "app.xml"]:
                path = os.path.join(temp_dir, "docProps", xml_file)
                if os.path.exists(path):
                    try:
                        tree = ET.parse(path)
                        root = tree.getroot()
                        for elem in root.iter():
                            elem.text = "" 
                        tree.write(path, encoding="utf-8", xml_declaration=True)
                    except ET.ParseError as e:
                        print(f" [AVERTISSEMENT] Erreur lors de la lecture XML : {e}")

            with zipfile.ZipFile(temp_file, "w") as z:
                for folder, _, files in os.walk(temp_dir):
                    for file in files:
                        fp = os.path.join(folder, file)
                        arc = os.path.relpath(fp, temp_dir)
                        z.write(fp, arc)

            shutil.move(temp_file, str(file_path)) 
        except zipfile.BadZipFile:
             print(" [ERREUR] Le fichier Office n'est pas un format ZIP valide.")
        except Exception as e:
            print(f" [ERREUR] Échec du nettoyage Office : {type(e).__name__}: {e}")
        finally:
            if os.path.exists(temp_dir):
                shutil.rmtree(temp_dir)

    def _clean_image_file(self, file_path: Path):
        """Ré-encode l'image pour perdre les métadonnées EXIF."""
        if not PILLOW_INSTALLED: return
        try:
            img = Image.open(str(file_path))
            data = list(img.getdata())
            # Créer une nouvelle image (méthode anti-EXIF classique)
            img2 = Image.new(img.mode, img.size) 
            img2.putdata(data)
            img2.save(str(file_path)) 
        except Exception as e:
             print(f" [ERREUR] Impossible de nettoyer l'image : {e}")


