    # ── Dimension 6 : supprimer structures IA (poids 0.10) ──────

    def _remove_ai_structure(self, text: str) -> str:
        """Convertit listes/titres Markdown en prose fluide."""
        lines = text.splitlines()
        prose_lines: list[str] = []
        for line in lines:
            line = re.sub(r'^#{1,6}\s+', '', line)          # titres ##
            line = re.sub(r'^\s*[-•*]\s+', '', line)        # puces
            line = re.sub(r'^\s*\d+[.)]\s+', '', line)      # 1. 2. 3.
            line = re.sub(r'\*\*(.*?)\*\*', r'\1', line)    # **gras**
            line = re.sub(r'\*(.*?)\*', r'\1', line)        # *italic*
            if line.strip():
                prose_lines.append(line.strip())
        # Joindre avec une espace (les virgules cassent la phrase trop court)
        joined = ' '.join(prose_lines)
        return re.sub(r' {2,}', ' ', joined).strip()

    # ── Dimension 3 : supprimer marqueurs IA (poids 0.20) ───────

    def _remove_ai_markers(self, text: str) -> str:
        """Remplace marqueurs IA détectés par des variantes neutres."""
        # D'abord les phrases longues du dict
        for phrase, choices in self._MARKER_REPLACEMENTS.items():
            pattern = r'\b' + re.escape(phrase) + r'\b'
            text = re.sub(pattern, lambda _, c=choices: random.choice(c), text, flags=re.IGNORECASE)
        # Puis les regexes larges du détecteur pour ce qui reste
        text = self._DET_AI_MARKERS.sub(lambda m: self._MARKER_REPLACEMENTS.get(
            m.group(0).lower(), [m.group(0)])[0], text)
        return text

    def _reduce_tone_density(self, text: str) -> str:
        """
        Dimension 8 (poids 0.05) : réduit la densité des mots
        overconfident ET hedging — les deux font monter le score IA.
        """
        # Overconfident → formulations plus nuancées (qui ne sont pas dans la liste)
        overconf_repl = {
            r"\btoujours\b":           ["souvent", "en règle générale", "généralement"],
            r"\bjamais\b":             ["rarement", "quasiment jamais", "très peu"],
            r"\bsans aucun doute\b":   ["assez clairement", "de façon assez évidente"],
            r"\bil est certain\b":     ["il semble", "on peut penser", "il paraît"],
        }
        for pat, choices in overconf_repl.items():
            text = re.sub(pat, lambda _, c=choices: random.choice(c), text, flags=re.I)

        # Hedging → affirmations directes
        hedge_repl = {
            r"\bpeut-être\b":              ["probablement", "sans doute"],
            r"\bil semblerait\b":          ["il semble", "on constate que"],
            r"\bon pourrait dire\b":       ["on dit", "on considère"],
            r"\bdans une certaine mesure\b": ["en partie", "assez largement"],
        }
        for pat, choices in hedge_repl.items():
            text = re.sub(pat, lambda _, c=choices: random.choice(c), text, flags=re.I)
        return text

    # ── Dimensions 1 & 5 : enrichir le vocabulaire ──────────────
    #    Perplexité lex. (0.20) = entropie Shannon → plus de types uniques
    #    Diversité lexicale (0.10) = CTTR = types / √(2×tokens)

    def _enrich_vocabulary(self, text: str, rate: float = 0.45) -> str:
        """
        Remplace aléatoirement des mots courants par des synonymes variés.
        Augmente simultanément l'entropie (perplexité) et le CTTR.
        """
        for pattern, choices in self._VOCAB_EXPANSION:
            def _repl(m: re.Match, c: list[str] = choices) -> str:
                if random.random() > rate:
                    return m.group(0)
                repl = random.choice(c)
                return repl[0].upper() + repl[1:] if m.group(0)[0].isupper() else repl
            text = re.sub(pattern, _repl, text, flags=re.IGNORECASE)
        return text

    # ── Dimensions 2 & 7 : varier la structure des phrases ──────
    #    Uniformité (0.15) = CV des longueurs → CV élevé = humain
    #    Burstiness (0.10) = Gini des longueurs → Gini élevé = humain

    def _split_sentences(self, text: str) -> list[str]:
        parts = re.split(r'(?<=[.!?…])\s+', text)
        return [p.strip() for p in parts if p.strip()]

    def _maximize_burstiness(self, sentences: list[str]) -> list[str]:
        """
        Crée une distribution très inégale des longueurs (Gini élevé) :
        - Coupe les phrases longues (> 20 mots) → 2 phrases courtes
        - Fusionne des paires de phrases très courtes (< 5 mots)
        - Insère des phrases ultra-courtes (3-5 mots) toutes les 3-4 phrases
        """
        result: list[str] = []
        i = 0
        insert_short_every = random.randint(3, 5)

        while i < len(sentences):
            s = sentences[i]
            words = s.split()
            n = len(words)

            # Couper les longues (> 20 mots)
            if n > 20 and random.random() < 0.75:
                # Cherche une virgule proche du milieu
                mid = n // 2
                cut = mid
                for k in range(max(1, mid - 4), min(n - 1, mid + 5)):
                    if words[k].endswith(','):
                        cut = k + 1
                        break
                part1 = " ".join(words[:cut]).rstrip(',') + "."
                part2 = " ".join(words[cut:])
                if part2 and part2[0].islower():
                    part2 = part2[0].upper() + part2[1:]
                result.append(part1)
                if part2.strip():
                    result.append(part2)
                i += 1
                continue

            # Fusionner deux phrases ultra-courtes consécutives (< 5 mots chacune)
            if (n < 5 and i + 1 < len(sentences)
                    and len(sentences[i + 1].split()) < 5):
                glue = random.choice([", et ", " — et pourtant ", ", donc "])
                merged = s.rstrip('.!?') + glue + sentences[i + 1][0].lower() + sentences[i + 1][1:]
                result.append(merged)
                i += 2
                continue

            result.append(s)

            # Insérer une phrase très courte périodiquement
            if (len(result) % insert_short_every == 0
                    and i < len(sentences) - 1):
                shorts = [
                    "C'est clair.", "Pas anodin.", "Ça compte.",
                    "Simple, non ?", "Et c'est tout.", "Voilà l'idée.",
                    "On y reviendra.", "À noter.", "Pas si simple.",
                    "C'est là le nœud.", "Ça mérite réflexion.",
                ]
                result.append(random.choice(shorts))
                insert_short_every = random.randint(3, 5)  # varier le rythme

            i += 1

        return result

    # ── Dimension 4 : richesse ponctuation (poids 0.10) ─────────
    #    Détecteur cherche : [—–…]|\.{3}|!{2,}|\?{2,}
    #    Score IA élevé si densité BASSE → on doit en injecter

    def _inject_human_punctuation(self, sentences: list[str]) -> list[str]:
        """
        Injecte tirets cadratins, ellipses, et doubles ponctuations
        — exactement ce que le détecteur compte comme signes humains.
        """
        result: list[str] = []
        for s in sentences:
            r = random.random()
            if r < 0.18:
                # Remplacer un point par une ellipse en fin de phrase
                s = re.sub(r'\.$', '…', s)
            elif r < 0.30:
                # Insérer un tiret cadratin au milieu d'une phrase longue
                words = s.split()
                if len(words) > 6:
                    pos = random.randint(len(words) // 3, 2 * len(words) // 3)
                    words.insert(pos, '—')
                    s = " ".join(words)
            elif r < 0.36:
                # Double point d'exclamation sur les affirmations fortes
                if s.endswith('.') and any(
                    w in s.lower() for w in ['incroyable', 'essentiel', 'crucial', 'remarquable', 'évident']
                ):
                    s = s[:-1] + '!!'
            result.append(s)
        return result

    # ── Pipeline complet ─────────────────────────────────────────

    def _humanize_core(self, text: str, strength: float = 0.5) -> str:
        """
        Pipeline qui attaque toutes les dimensions dans l'ordre optimal.
        strength ∈ [0.2, 0.9] contrôle l'agressivité globale.
        """
        # 1. Supprimer la structure IA (dim 6, poids 0.10)
        text = self._remove_ai_structure(text)

        # 2. Supprimer marqueurs IA (dim 3, poids 0.20 — poids le plus haut avec perplexité)
        text = self._remove_ai_markers(text)

        # 3. Réduire le ton assertif/prudent (dim 8, poids 0.05)
        text = self._reduce_tone_density(text)

        # 4. Enrichir le vocabulaire (dims 1 + 5, poids 0.30 cumulé)
        text = self._enrich_vocabulary(text, rate=strength * 0.8)

        # 5. Varier la structure des phrases (dims 2 + 7, poids 0.25 cumulé)
        sentences = self._split_sentences(text)
        sentences = self._maximize_burstiness(sentences)

        # 6. Injecter ponctuation humaine (dim 4, poids 0.10)
        sentences = self._inject_human_punctuation(sentences)

        # 7. Recomposer + nettoyer
        text = " ".join(sentences)
        text = re.sub(r' ([,;:.!?…])', r'\1', text)   # espaces avant ponctuation
        text = re.sub(r' {2,}', ' ', text)             # espaces multiples
        text = re.sub(r'\s*—\s*', ' — ', text)         # tirets bien espacés
        return text.strip()

