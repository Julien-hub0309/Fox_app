    def humanize(self, file_path: Path, mode: str="subtil") -> bool:
        """Point d'entrée principal pour humaniser un fichier."""
        print(f"\n[HUMANISATION] Démarrage du nettoyage de {file_path} dans le mode : {mode.upper()}")
        try:
            # 1. Lecture brute (Assure que l'on copie le contenu, jamais en place)
            with open(str(file_path), 'r', encoding='utf-8', errors='ignore') as f:
                text = f.read()
            
            # 2. Transformation
            humanized_text = self._human_targeted(text, mode) 
            
            # 3. Écrasement du fichier original (écriture en place garantie de la modifcation)
            with open(str(file_path), 'w', encoding='utf-8') as f:
                f.write(humanized_text)
            print(f"[SUCCÈS] Le fichier a été modifié et sauvegardé.")
            return True

        except Exception as e:
             print(f" [ERREUR] Échec de l'humanisation du contenu : {type(e).__name__}: {e}")
             return False


    def humanize_batch(self, file_paths: list[Path], mode: str = "subtil") -> list[tuple[str, bool]]:
        """Humanise plusieurs fichiers avec le même mode."""
        results = []
        for file_path in file_paths:
            if self.humanize(file_path, mode):
                results.append((str(file_path), True))
            else:
                results.append((str(file_path), False))
        return results

    def humanize_directory(self, directory_path: str, mode: str = "subtil", recursive: bool = True) -> list[tuple[str, Path]]:
        """Humanise tous les fichiers dans un répertoire."""
        if not os.path.exists(directory_path):
            print(f" [ERREUR] Le répertoire n'existe pas: {directory_path}")
            return []
        
        print(f"\n[BATCH HUMANIZATION] Démarrage pour le répertoire: {directory_path} (mode: {mode})")
        results = []
        for root, dirs, files in os.walk(directory_path):
            for filename in files:
                file_path = Path(os.path.join(root, filename))
                ext = file_path.suffix.lower()
                if ext in self.text_extensions:
                    self.humanize(file_path, mode) 
                    results.append((str(file_path), file_path))
        return results